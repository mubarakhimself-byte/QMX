"""Write slices/<id>/CHAIN.md for every slice: the part of the chain its builder needs.

Usage: python chain_packet.py <program folder>

Generated at handoff; nobody edits a packet by hand. Each packet holds only what the
slice's `Chain:` line cites, plus what touches its files: his ask with its source, the plan
lines (with any "my reading"), the architecture elements and the operations lines that name
them, the edge cases in full, the can-change rows it carries out, the removed rows for its
files ("never rebuild"), the ground facts and fixed lines that name its files, and its
neighbours (slices sharing an element or an edge case). Standard library only.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PROJECT_REMOVED = Path("C:/Users/Mubarak/Desktop/QMX/tracker/REMOVED.md")


def read(path: Path) -> str:
    return path.read_text("utf-8", errors="replace") if path.exists() else ""


def bullets(text: str, ident: str) -> list[str]:
    """Bullet lines (with their continuation lines) whose bold id is `ident`."""
    out, lines = [], text.splitlines()
    for i, ln in enumerate(lines):
        if re.match(rf"^\s*-\s*\*\*{re.escape(ident)}\.?\*\*", ln):
            block = [ln]
            for nxt in lines[i + 1:]:
                if nxt.startswith("  ") and not re.match(r"^\s*-\s*\*\*", nxt):
                    block.append(nxt)
                else:
                    break
            out.append("\n".join(block))
    return out


def section(text: str, title: str) -> str:
    m = re.search(rf"^##+ {re.escape(title)}[^\n]*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    return m.group(1).strip() if m else ""


def slices(program: Path) -> list[dict]:
    text = read(program / "SLICES.md")
    header = next((ln for ln in text.splitlines() if ln.lstrip().startswith("|") and "depends on" in ln.lower()), "")
    cols = [c.strip().casefold() for c in header.strip().strip("|").split("|")]
    rows, started = [], False
    for ln in text.splitlines():
        if ln == header:
            started = True
            continue
        if not started:
            continue
        if not ln.lstrip().startswith("|"):
            break
        cells = [c.strip().strip("`") for c in ln.strip().strip("|").split("|")]
        if len(cells) == len(cols) and not set(cells[0]) <= set("-: "):
            rows.append(dict(zip(cols, cells)))
    return rows


def path_hits(text_block: str, files: list[str]) -> bool:
    for f in files:
        stem = f.rstrip("*").rstrip("/")
        if stem and stem in text_block:
            return True
    return False


def facts_naming(ground: str, files: list[str]) -> list[str]:
    blocks = re.findall(r"^```fact .*?^```", ground, re.M | re.S)
    return [b for b in blocks if path_hits(b, files)]


def main(program: Path) -> int:
    scope, plan, arch = read(program / "SCOPE.md"), read(program / "PLAN.md"), read(program / "arch" / "ARCH.md")
    edges, changes, ground = read(program / "EDGE-CASES.md"), read(program / "CAN-CHANGE.md"), read(program / "GROUND.md")
    removed = read(program / "REMOVED.md") + "\n" + read(PROJECT_REMOVED)
    rows = slices(program)
    chains: dict[str, dict[str, set[str]]] = {}
    for row in rows:
        brief = read(program / "slices" / row["id"] / "BRIEF.md")
        m = re.search(r"^Chain:(.*)$", brief, re.M)
        line = m.group(1) if m else ""
        chains[row["id"]] = {
            "plan": set(re.findall(r"\bS\d+\.[a-z]+\b", line)),
            "arch": set(re.findall(r"\bA\d+\b", line)),
            "edges": set(re.findall(r"\bE\d+\b", line)),
            "changes": set(re.findall(r"\bX\d+\b", line)),
        }
    ops = section(arch, "Operations")
    written = 0
    for row in rows:
        sid, c = row["id"], chains[row["id"]]
        files = [f.strip() for f in row.get("files", "").split(",") if f.strip()]
        ask = row.get("ask", "").strip()
        parts = [f"# Chain packet: {sid}", "",
                 "Generated by `standing/funnel/chain_packet.py` at handoff. Do not edit; rerun the script.", ""]
        parts += ["## His ask", *bullets(scope, ask), ""]
        parts += ["## Plan lines", *[b for p in sorted(c["plan"]) for b in bullets(plan, p)], ""]
        arch_lines = [b for a in sorted(c["arch"]) for b in bullets(arch, a)]
        op_lines = [ln for ln in ops.splitlines() if any(re.search(rf"\b{a}\b", ln) for a in c["arch"])]
        parts += ["## Architecture elements", *arch_lines, "", "### Operations they carry", *(op_lines or ["none named"]), ""]
        parts += ["## Edge cases", *[b for e in sorted(c["edges"], key=lambda x: int(x[1:])) for b in bullets(edges, e)], ""]
        parts += ["## Can-change rows it carries out", *([b for x in sorted(c["changes"]) for b in bullets(changes, x)] or ["none"]), ""]
        never = [ln for ln in removed.splitlines() if ln.lstrip().startswith("- **R") and path_hits(ln, files)]
        parts += ["## Never rebuild (removed rows on its files)", *(never or ["none"]), ""]
        fixed = [ln for ln in section(ground, "Fixed lines touched").splitlines() if path_hits(ln, files)]
        parts += ["## Fixed lines on its files", *(fixed or ["none"]), ""]
        parts += ["## Ground facts on its files", *(facts_naming(ground, files) or ["none"]), ""]
        neighbours = sorted(o for o, oc in chains.items() if o != sid and (oc["arch"] & c["arch"] or oc["edges"] & c["edges"]))
        parts += ["## Neighbours (share an element or an edge case)", ", ".join(neighbours) or "none", ""]
        out = program / "slices" / sid / "CHAIN.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("\n".join(parts), encoding="utf-8")
        written += 1
    print(f"wrote {written} chain packets")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1])))
